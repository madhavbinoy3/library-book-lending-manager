import { useState, useEffect } from 'react';
import { AlertCircle } from 'lucide-react';
import Modal from './Modal';
import { api } from '../api/client';
import { BOOK_CATEGORIES } from '../utils/constants';

const INITIAL_FORM = {
  title: '',
  author: '',
  isbn: '',
  category: 'Fiction',
  totalCopies: '1',
};

export default function AddBookModal({ isOpen, onClose, onSuccess }) {
  const [form, setForm] = useState(INITIAL_FORM);
  const [fieldErrors, setFieldErrors] = useState({});
  const [serverError, setServerError] = useState('');
  const [submitting, setSubmitting] = useState(false);

  useEffect(() => {
    if (isOpen) {
      setForm(INITIAL_FORM);
      setFieldErrors({});
      setServerError('');
      setSubmitting(false);
    }
  }, [isOpen]);

  const validate = () => {
    const errors = {};
    if (!form.title.trim()) errors.title = 'Title is required';
    if (!form.author.trim()) errors.author = 'Author is required';

    const isbn = form.isbn.trim();
    if (!/^(\d{10}|\d{13})$/.test(isbn)) {
      errors.isbn = 'ISBN must contain exactly 10 or 13 digits';
    }

    if (!BOOK_CATEGORIES.includes(form.category)) {
      errors.category = 'Please select a valid category';
    }

    const copies = Number(form.totalCopies);
    if (!Number.isInteger(copies) || copies < 1 || copies > 20) {
      errors.totalCopies = 'Total copies must be a whole number between 1 and 20';
    }

    setFieldErrors(errors);
    return Object.keys(errors).length === 0;
  };

  const handleChange = (field, value) => {
    setForm((prev) => ({ ...prev, [field]: value }));
    if (fieldErrors[field]) {
      setFieldErrors((prev) => ({ ...prev, [field]: '' }));
    }
    if (serverError) setServerError('');
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setServerError('');
    if (!validate()) return;

    setSubmitting(true);
    try {
      const response = await api.createBook({
        title: form.title.trim(),
        author: form.author.trim(),
        isbn: form.isbn.trim(),
        category: form.category,
        totalCopies: Number(form.totalCopies),
      });
      onSuccess(response.data, response.message);
      onClose();
    } catch (err) {
      setServerError(err.message || 'Failed to add book');
      if (err.status === 409) {
        setFieldErrors((prev) => ({ ...prev, isbn: err.message }));
      }
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <Modal
      isOpen={isOpen}
      onClose={onClose}
      title="Add New Book"
      subtitle="Book code (LB-CAT-###) will be auto-generated by the system."
    >
      <form onSubmit={handleSubmit} className="space-y-4" noValidate>
        {serverError && (
          <div className="flex items-start gap-2.5 rounded-lg border border-red-200 bg-red-50 px-3.5 py-2.5 text-sm text-red-800">
            <AlertCircle className="mt-0.5 h-4 w-4 shrink-0 text-red-600" />
            <span>{serverError}</span>
          </div>
        )}

        <div>
          <label htmlFor="add-title" className="block text-sm font-medium text-slate-700">
            Title <span className="text-red-500">*</span>
          </label>
          <input
            id="add-title"
            type="text"
            value={form.title}
            onChange={(e) => handleChange('title', e.target.value)}
            placeholder="e.g. Clean Code"
            className={`mt-1 w-full rounded-lg border px-3 py-2 text-sm shadow-2xs focus:outline-none focus:ring-2 ${
              fieldErrors.title
                ? 'border-red-300 focus:border-red-500 focus:ring-red-200'
                : 'border-slate-300 focus:border-indigo-500 focus:ring-indigo-200'
            }`}
          />
          {fieldErrors.title && <p className="mt-1 text-xs text-red-600">{fieldErrors.title}</p>}
        </div>

        <div>
          <label htmlFor="add-author" className="block text-sm font-medium text-slate-700">
            Author <span className="text-red-500">*</span>
          </label>
          <input
            id="add-author"
            type="text"
            value={form.author}
            onChange={(e) => handleChange('author', e.target.value)}
            placeholder="e.g. Robert C. Martin"
            className={`mt-1 w-full rounded-lg border px-3 py-2 text-sm shadow-2xs focus:outline-none focus:ring-2 ${
              fieldErrors.author
                ? 'border-red-300 focus:border-red-500 focus:ring-red-200'
                : 'border-slate-300 focus:border-indigo-500 focus:ring-indigo-200'
            }`}
          />
          {fieldErrors.author && <p className="mt-1 text-xs text-red-600">{fieldErrors.author}</p>}
        </div>

        <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
          <div>
            <label htmlFor="add-isbn" className="block text-sm font-medium text-slate-700">
              ISBN <span className="text-red-500">*</span>
            </label>
            <input
              id="add-isbn"
              type="text"
              inputMode="numeric"
              value={form.isbn}
              onChange={(e) => handleChange('isbn', e.target.value)}
              placeholder="10 or 13 digits"
              className={`mt-1 w-full rounded-lg border px-3 py-2 text-sm shadow-2xs focus:outline-none focus:ring-2 ${
                fieldErrors.isbn
                  ? 'border-red-300 focus:border-red-500 focus:ring-red-200'
                  : 'border-slate-300 focus:border-indigo-500 focus:ring-indigo-200'
              }`}
            />
            {fieldErrors.isbn ? (
              <p className="mt-1 text-xs text-red-600">{fieldErrors.isbn}</p>
            ) : (
              <p className="mt-1 text-xs text-slate-400">Digits only (10 or 13 digits)</p>
            )}
          </div>

          <div>
            <label htmlFor="add-category" className="block text-sm font-medium text-slate-700">
              Category <span className="text-red-500">*</span>
            </label>
            <select
              id="add-category"
              value={form.category}
              onChange={(e) => handleChange('category', e.target.value)}
              className="mt-1 w-full rounded-lg border border-slate-300 bg-white px-3 py-2 text-sm shadow-2xs focus:border-indigo-500 focus:outline-none focus:ring-2 focus:ring-indigo-200"
            >
              {BOOK_CATEGORIES.map((cat) => (
                <option key={cat} value={cat}>
                  {cat}
                </option>
              ))}
            </select>
            {fieldErrors.category && (
              <p className="mt-1 text-xs text-red-600">{fieldErrors.category}</p>
            )}
          </div>
        </div>

        <div>
          <label htmlFor="add-copies" className="block text-sm font-medium text-slate-700">
            Total Copies <span className="text-red-500">*</span>
          </label>
          <input
            id="add-copies"
            type="number"
            min={1}
            max={20}
            step={1}
            value={form.totalCopies}
            onChange={(e) => handleChange('totalCopies', e.target.value)}
            className={`mt-1 w-full rounded-lg border px-3 py-2 text-sm shadow-2xs focus:outline-none focus:ring-2 ${
              fieldErrors.totalCopies
                ? 'border-red-300 focus:border-red-500 focus:ring-red-200'
                : 'border-slate-300 focus:border-indigo-500 focus:ring-indigo-200'
            }`}
          />
          {fieldErrors.totalCopies ? (
            <p className="mt-1 text-xs text-red-600">{fieldErrors.totalCopies}</p>
          ) : (
            <p className="mt-1 text-xs text-slate-400">Allowed range: 1 to 20 copies</p>
          )}
        </div>

        <div className="flex items-center justify-end gap-3 border-t border-slate-100 pt-4">
          <button
            type="button"
            onClick={onClose}
            className="rounded-lg border border-slate-300 bg-white px-4 py-2 text-sm font-medium text-slate-700 transition hover:bg-slate-50 cursor-pointer"
          >
            Cancel
          </button>
          <button
            type="submit"
            disabled={submitting}
            className="rounded-lg bg-indigo-600 px-4 py-2 text-sm font-semibold text-white shadow-xs transition hover:bg-indigo-700 disabled:opacity-60 cursor-pointer"
          >
            {submitting ? 'Adding...' : 'Add Book'}
          </button>
        </div>
      </form>
    </Modal>
  );
}
